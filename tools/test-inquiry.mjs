import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";

// 防止伪造来源、坏存档和反馈与学生原稿错配后仍被显示。
const inquiry = await import("../js/inquiry.js").catch(() => ({}));
assert.equal(typeof inquiry.createInquiry, "function", "探究状态与证据行为尚未实现");
assert.equal(typeof inquiry.inquiryStageAllowed, "function", "步骤切换不能绕过原稿与资料要求");
const task = JSON.parse(await readFile(new URL("../story/inquiry.json", import.meta.url), "utf8"));
const fresh = inquiry.createInquiry(task);
assert.equal(inquiry.inquiryStageAllowed(fresh, 2, task), false);
assert.equal(inquiry.inquiryStageAllowed({ ...fresh, initial: "原稿" }, 3, task), false);
assert.equal(inquiry.inquiryStageAllowed({ ...fresh, initial: "原稿", sourceIds: ["lubiao"] }, 4, task), false);
assert.equal(inquiry.inquiryStageAllowed({ ...fresh, initial: "原稿", sourceIds: ["lubiao"], revision: "修改" }, 4, task), true);
assert.equal(inquiry.inquiryStageAllowed({ ...fresh, initial: "原稿", sourceIds: ["fake"], revision: "修改" }, 3, task), false);
assert.equal(fresh.stage, 1);
assert.equal(fresh.initial, "");
assert.equal(inquiry.restoreInquiry("not json", task).stage, 1);
assert.equal(inquiry.restoreInquiry(JSON.stringify({ ...fresh, stage: 88 }), task).stage, 1);
assert.equal(inquiry.restoreInquiry(JSON.stringify({ ...fresh, taskVersion: "old", initial: "旧稿" }), task).initial, "");
const restored = inquiry.restoreInquiry(JSON.stringify({ ...fresh, stage: 3, initial: "我的解释", sourceIds: ["lubiao", "fake", "lubiao"], revision: "修改后" }), task);
assert.deepEqual(restored.sourceIds, ["lubiao"]);
assert.equal(restored.initial, "我的解释");
assert.equal(restored.revision, "修改后");
assert.equal(inquiry.restoreInquiry(JSON.stringify({ ...fresh, stage: 4, initial: "", revision: "" }), task).stage, 1);
const draft = { ...fresh, stage: 2, initial: "红布是不是统一使用的？", sourceIds: ["lubiao"] };
const request = inquiry.inquiryRequest(draft, task);
assert.deepEqual(request, { taskId: "signpost-evidence", initial: "红布是不是统一使用的？", initialBoundary: "unsure", sourceIds: ["lubiao"], supportNeed: "boundary" });
assert.equal(inquiry.feedbackFor({ observation: "看一看史料", evidenceNote: "红布是艺术设计", question: "哪些内容有依据？", sourceIds: ["fake"] }, task), null);
assert.equal(inquiry.feedbackFor({ observation: "", evidenceNote: "依据", question: "问题", sourceIds: ["lubiao"] }, task), null);
assert.equal(inquiry.feedbackFor({ observation: "提示", evidenceNote: "依据", question: "问题", sourceIds: [] }, task), null);
assert.equal(inquiry.feedbackFor({ observation: "提示", evidenceNote: "依据", question: "问题", sourceIds: ["lubiao"] }, task).sourceIds[0], "lubiao");
const completed = { ...draft, stage: 4, revision: "红布是剧本设计，我需要用史料区分探路与纪念。", revisionBoundary: "fiction" };
const text = inquiry.inquiryText(completed, task, { lubiao: { title: "拐棍碑", text: "整理内容", sourceTitle: "来源", sourceUrl: "https://example.org/source" } });
assert.ok(text.includes(draft.initial));
assert.ok(text.includes(completed.revision));
assert.ok(text.includes("https://example.org/source"));
assert.ok(text.includes("没有生成 AI 反馈"));
assert.ok(!text.includes("得分"));
console.log("探究行为通过：坏存档、来源白名单、原稿保留、反馈边界与成果导出。");
