import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
const inquiry = await import("../js/inquiry.js");
const task = JSON.parse(await readFile(new URL("../story/inquiry.json", import.meta.url), "utf8"));
assert.equal(typeof inquiry.commitInquiryInitial, "function", "需要先保留并锁定原始解释");
const fresh = inquiry.createInquiry(task, 500);
const committed = inquiry.commitInquiryInitial({ ...fresh, initial: "我以为红布路标是统一规定。", initialBoundary: "fact" }, 1000);
assert.equal(committed.initialCommitted, true);
const second = inquiry.commitInquiryInitial({ ...committed, initial: "被替换的文字" }, 2000);
assert.equal(second.initial, "我以为红布路标是统一规定。");
assert.equal(second.initialBoundary, "fact");
const draft = { ...committed, stage: 4, sourceIds: ["lubiao"], revision: "资料把红布路标说明为艺术设计，不能证明统一规定。", revisionBoundary: "fiction", supportNeed: "evidence", evidenceNote: "资料卡说红布引路是艺术设计。", changeReason: "我不再把故事画面直接当成史实。" };
const request = inquiry.inquiryRequest(draft, task);
assert.equal(request.supportNeed, "evidence");
assert.equal(request.initial, "我以为红布路标是统一规定。");
assert.ok(inquiry.inquirySupportHint({ ...draft, supportNeed: "boundary" }, task).includes("创作"));
assert.notEqual(inquiry.inquirySupportHint({ ...draft, supportNeed: "boundary" }, task), inquiry.inquirySupportHint({ ...draft, supportNeed: "evidence" }, task));
const record = inquiry.buildInquiryRecord(draft, task, 3000);
assert.equal(record.schema, "grassland-inquiry-record");
assert.equal(record.initial, committed.initial);
assert.equal(record.revision, draft.revision);
assert.equal(record.evidenceNote, draft.evidenceNote);
assert.equal(record.changeReason, draft.changeReason);
assert.equal(record.aiFeedbackReceived, false);
assert.equal(record.completedAt, 3000);
assert.ok(record.recordId);
const lockedRestored = inquiry.restoreInquiry(JSON.stringify({ ...draft, initial: "伪改原稿", initialBoundary: "unsure" }), task);
assert.equal(lockedRestored.initial, committed.initial);
assert.equal(lockedRestored.initialBoundary, "fact");
assert.equal(inquiry.buildInquiryRecord({ ...fresh, stage: 1 }, task, 3000), null);
console.log("学习记录通过：初稿锁定、帮助方向、依据与修改理由、结构化成果与旧稿恢复。");
