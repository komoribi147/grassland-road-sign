"""Create reproducible, content-addressed web images; keep PNG masters intact.

Run with Python + Pillow: python tools/optimize-images.py
"""
from concurrent.futures import ThreadPoolExecutor
from hashlib import sha256
from pathlib import Path
import json
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "assets" / "optimized"
OUT.mkdir(parents=True, exist_ok=True)


def convert(source):
    record = {"originalBytes": source.stat().st_size}
    with Image.open(source) as raw:
        image = ImageOps.exif_transpose(raw).convert("RGB")
        record["width"], record["height"] = image.size
        for tier, limit in [("full", 1920), ("small", 960)]:
            resized = image.copy()
            resized.thumbnail((limit, limit), Image.Resampling.LANCZOS)
            from io import BytesIO
            encoded = BytesIO()
            resized.save(encoded, "WEBP", quality=85, method=6)
            data = encoded.getvalue()
            fingerprint = sha256(data).hexdigest()[:12]
            name = f"{source.stem}-{tier}-{fingerprint}.webp"
            (OUT / name).write_bytes(data)
            record[tier] = f"assets/optimized/{name}"
            record[tier + "Bytes"] = len(data)
    return source.relative_to(ROOT).as_posix(), record


sources = sorted((ROOT / "assets" / "stills").glob("*.png"))
with ThreadPoolExecutor(max_workers=4) as pool:
    records = dict(pool.map(convert, sources))
body = json.dumps(records, ensure_ascii=False, indent=2)
release = sha256(body.encode()).hexdigest()[:12]
(ROOT / "js" / "image-assets.js").write_text(
    "// Generated by tools/optimize-images.py; do not edit.\n"
    + f'export const IMAGE_RELEASE = "{release}";\n'
    + "export const IMAGE_ASSETS = " + body + ";\n", encoding="utf-8"
)
before = sum(r["originalBytes"] for r in records.values())
full = sum(r["fullBytes"] for r in records.values())
small = sum(r["smallBytes"] for r in records.values())
print(json.dumps({"images": len(records), "release": release,
                  "originalMiB": round(before / 1048576, 2),
                  "fullMiB": round(full / 1048576, 2),
                  "smallMiB": round(small / 1048576, 2),
                  "fullReduction": f"{(1-full/before)*100:.1f}%"}, ensure_ascii=False))
