import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import * as inquiry from "../js/inquiry.js";
const task = JSON.parse(await readFile(new URL("../story/inquiry.json", import.meta.url), "utf8"));
assert.equal(typeof inquiry.groundInquiryFeedback, "function", "新反馈需要核对学生原话并使用固定资料摘录");
const initial = "我觉得路标能给后来的人指路，所以猜当年统一使用红布路标。";
const generated = { studentQuote: "我觉得路标能给后来的人指路", observation: "你把故事里的作用与当年的统一做法联系起来了。", evidenceNote: "现有资料不足以证明统一做法。", question: "资料中哪句话区分了创作与记载？", evidenceIds: ["signpost-design"] };
const result = inquiry.groundInquiryFeedback(generated, task, initial, "test-model");
assert.equal(result.version, 2);
assert.equal(result.studentQuote, generated.studentQuote);
assert.equal(result.citations[0].sourceId, "lubiao");
assert.equal(result.citations[0].excerpt, "剧中绑红布引路的木棍是受这些记载启发的艺术设计。");
assert.ok(result.citations[0].scope.includes("不能"));
assert.equal(result.model, "test-model");
assert.equal(inquiry.groundInquiryFeedback({ ...generated, studentQuote: "学生从没说过的原话" }, task, initial, "m"), null);
assert.equal(inquiry.groundInquiryFeedback({ ...generated, evidenceIds: ["invented"] }, task, initial, "m"), null);
assert.equal(inquiry.groundInquiryFeedback({ ...generated, evidenceIds: [] }, task, initial, "m"), null);
assert.equal(inquiry.feedbackFor({ ...result, citations: [{ ...result.citations[0], excerpt: "伪造的摘录" }] }, task, initial), null);
assert.equal(inquiry.feedbackFor({ ...result, studentQuote: "换了学生原话" }, task, initial), null);
const legacy = inquiry.feedbackFor({ observation: "旧回应", evidenceNote: "旧解释", question: "旧问题", sourceIds: ["lubiao"] }, task, initial);
assert.ok(legacy, "保留旧反馈，不伪造新引用");
assert.equal(legacy.citations, undefined);
const lines = inquiry.inquiryFeedbackText(result, task, {});
assert.ok(lines.join("\n").includes(generated.studentQuote));
assert.ok(lines.join("\n").includes(result.citations[0].excerpt));
assert.ok(lines.join("\n").includes(result.citations[0].scope));
console.log("反馈依据通过：原话定位、固定摘录、未知证据拒绝、导入篡改拒绝、旧反馈保留与导出。");
