import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { createInquiry, commitInquiryInitial, buildInquiryRecord, groundInquiryFeedback } from "../js/inquiry.js";
const review = await import("../js/classroom-review.js").catch(() => ({}));
assert.equal(typeof review.importLearningRecords, "function", "需要能收集真实匿名成果的教师记录工具");
const task = JSON.parse(await readFile(new URL("../story/inquiry.json", import.meta.url), "utf8"));
const draft = { ...commitInquiryInitial({ ...createInquiry(task, 1000), initial: "我猜红布路标是统一使用的。" }, 2000), stage: 4, sourceIds: ["lubiao"], revision: "这部分是艺术设计，不能用来证明统一规定。", changeReason: "资料改变了我的依据。" };
const record = buildInquiryRecord(draft, task, 3000);
const empty = review.createReviewState();
assert.equal(empty.cases.length, 0, "不能预填虚构学生数据");
const first = review.importLearningRecords(empty, JSON.stringify(record), task);
assert.equal(first.added, 1);
assert.equal(first.state.cases[0].record.initial, draft.initial);
assert.equal(first.state.cases[0].observation.boundary, "pending", "教师观察不能由学生选项自动推断");
assert.equal(review.importLearningRecords(first.state, JSON.stringify(record), task).added, 0);
assert.equal(review.importLearningRecords(first.state, JSON.stringify(record), task).duplicates, 1);
assert.throws(() => review.importLearningRecords(first.state, "broken", task));
assert.throws(() => review.importLearningRecords(first.state, JSON.stringify({ ...record, sourceIds: ["fake"] }), task));
assert.throws(() => review.importLearningRecords(first.state, JSON.stringify({ ...record, completedAt: 1 }), task));
assert.throws(() => review.importLearningRecords(first.state, JSON.stringify({ ...record, aiFeedbackReceived: true, feedback: null }), task));
assert.equal(first.state.cases.length, 1, "坏文件不得改写已有数据");
first.state.cases[0].alias = "S01";
Object.assign(first.state.cases[0].observation, { boundary: "visible", evidence: "followup", revision: "visible", classroom: "adjust", misconceptions: ["evidence"], note: "学生能指出创作，但还需解释所选资料与观点的关系。" });
assert.deepEqual(review.reviewSummary(first.state), { total: 1, withAi: 0, observed: 1, followup: 1 });
const restored = review.restoreReviewState(JSON.stringify(first.state), task);
assert.equal(restored.cases[0].observation.evidence, "followup");
assert.equal(restored.cases[0].alias, "S01");
const backup = review.importLearningRecords(empty, JSON.stringify(first.state), task);
assert.equal(backup.state.cases[0].observation.note, first.state.cases[0].observation.note);
const report = review.reviewText(first.state, task);
assert.ok(report.includes("S01"));
assert.ok(report.includes(draft.initial));
assert.ok(report.includes("需要追问"));
assert.ok(report.includes("不能据此证明普遍教学效果"));
assert.equal(review.restoreReviewState("bad", task).cases.length, 0);
const feedback = groundInquiryFeedback({ studentQuote: draft.initial, observation: "你在把情境与制度联系起来。", evidenceNote: "现有资料不足以证明统一规定。", question: "哪句话说明这是艺术设计？", evidenceIds: ["signpost-design"] }, task, draft.initial, "test-model");
const withAi = { ...record, recordId: record.recordId + "-ai", aiFeedbackReceived: true, feedback };
const aiState = review.importLearningRecords(empty, JSON.stringify(withAi), task).state;
assert.equal(aiState.cases[0].observation.feedbackReview, "pending", "AI 建议是否有帮助应由教师核查");
aiState.cases[0].observation.feedbackReview = "needs-check";
aiState.cases[0].observation.feedbackNote = "需要提醒学生，缺少证据不等于历史上从未发生。";
const lore = JSON.parse(await readFile(new URL("../story/lore.json", import.meta.url), "utf8"));
const aiReport = review.reviewText(aiState, task, lore);
assert.ok(aiReport.includes(feedback.studentQuote));
assert.ok(aiReport.includes(feedback.question));
assert.ok(aiReport.includes(feedback.citations[0].excerpt));
assert.ok(aiReport.includes(lore.lubiao.sourceUrl));
assert.ok(aiReport.includes(aiState.cases[0].observation.feedbackNote));
assert.equal(review.restoreReviewState(JSON.stringify(aiState), task).cases[0].observation.feedbackReview, "needs-check");
assert.throws(() => review.importLearningRecords(empty, JSON.stringify({ ...withAi, feedback: { ...feedback, studentQuote: "并不是这名学生写下的原话" } }), task));
const classroom = review.createReviewState();
for (let index = 0; index < 100; index++) {
  const item = JSON.parse(JSON.stringify(aiState.cases[0]));
  item.record.recordId += "-class-" + index;
  item.record.initial += "想".repeat(780 - item.record.initial.length);
  item.record.revision = "理".repeat(780);
  item.record.evidenceNote = "据".repeat(480);
  item.record.changeReason = "改".repeat(480);
  item.observation.note = "观".repeat(980);
  item.observation.feedbackNote = "核".repeat(980);
  classroom.cases.push(item);
}
const largeBackup = JSON.stringify(classroom);
assert.ok(new TextEncoder().encode(largeBackup).length > 1024 * 1024, "覆盖正常整班备份超过单个学生文件限制的情况");
assert.equal(review.restoreReviewState(largeBackup, task).cases.length, 100, "刷新不能丢失合法整班记录");
assert.equal(review.importLearningRecords(empty, largeBackup, task).state.cases.length, 100, "整班备份必须能导回");
assert.throws(() => review.importLearningRecords(empty, JSON.stringify({ ...record, padding: "x".repeat(1024 * 1024) }), task), "单个学生记录仍限制为1 MB");
assert.equal(review.restoreReviewState("invalid stored record", task).restoreError, true, "恢复失败应明确标记，不能让界面静默覆盖");
console.log("教师试用记录通过：空状态、匿名成果导入、重复拒绝、损坏文件、人工观察、恢复与导出。");
